const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs=require('fs');
const assert=require('node:assert/strict');
const path=require('node:path');
const artifactRoot=process.env.MARKET_CHECK_OUTPUT || path.join(process.cwd(), '.market-check');
fs.mkdirSync(path.join(artifactRoot, 'outputs'),{recursive:true});
fs.mkdirSync(path.join(artifactRoot, 'work'),{recursive:true});
process.chdir(artifactRoot);
(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH ? {executablePath:process.env.CHROME_PATH} : {})});
 const report=[];
 for(const mobile of [false,true]){
  const context=await browser.newContext({viewport:mobile?{width:390,height:844}:{width:1440,height:1100},isMobile:mobile,hasTouch:mobile});
  const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(`${process.env.BASE_URL||'http://127.0.0.1:3001'}/team/1234567?tab=market`,{waitUntil:'domcontentloaded'});
  await page.locator('.market-table tbody tr[data-player-id]').first().waitFor({timeout:120000});
  await page.getByRole('heading',{name:'Injuries & bans',exact:true}).waitFor();
  await page.waitForTimeout(1500);
  assert.equal(await page.getByRole('button',{name:'Live',exact:true}).count(),0);
  const bootstrap=await page.request.get(`${process.env.BASE_URL||'http://127.0.0.1:3001'}/api/fpl/bootstrap`).then(r=>r.json());
  const ids=()=>page.locator('.market-table tbody tr[data-player-id]').evaluateAll(els=>els.map(e=>Number(e.dataset.playerId)));
  const lookup=new Map(bootstrap.elements.map(e=>[e.id,e]));
  const initial=await ids();assert(initial.length>0&&initial.length<=15);
  const descending=initial.map(id=>lookup.get(id).price_change_percent).filter(n=>n!=null);assert.deepEqual(descending,[...descending].sort((a,b)=>b-a));
  await page.getByRole('columnheader',{name:/Progress/}).getByRole('button').click();
  assert.equal(await page.getByRole('columnheader',{name:/Progress/}).getAttribute('aria-sort'),'ascending');
  const asc=(await ids()).map(id=>lookup.get(id).price_change_percent).filter(n=>n!=null);assert.deepEqual(asc,[...asc].sort((a,b)=>a-b));
  await page.getByRole('columnheader',{name:/Progress/}).getByRole('button').click();
  await page.locator('.market-filters').getByRole('button',{name:'All',exact:true}).click();
  await page.getByLabel('Search market players').fill('Haaland');assert.equal((await ids()).length,1);
  assert.match(await page.locator('.market-table tbody').innerText(),/Haaland/);
  await page.getByLabel('Market position').selectOption('2');assert.match(await page.locator('.market-table tbody').innerText(),/No players/);
  await page.getByLabel('Market position').selectOption('');await page.getByLabel('Search market players').fill('');
  await page.getByRole('columnheader',{name:/Player/}).getByRole('button').click();
  const names=(await ids()).map(id=>lookup.get(id).web_name);assert.deepEqual(names,[...names].sort((a,b)=>a.localeCompare(b)));
  await page.locator('.market-filters').getByRole('button',{name:'My team',exact:true}).click();
  await page.getByRole('button',{name:'GW changes',exact:true}).click();assert(await page.getByRole('columnheader',{name:/This GW/}).count());
  await page.getByRole('button',{name:'Forecasts',exact:true}).click();
  const news=page.locator('.market-news-row');assert((await news.count())>0);await news.first().locator('summary').click();assert.equal(await news.first().getAttribute('open'),'');
  await page.getByLabel('Search injury updates').fill('zzzzzz');assert.match(await page.locator('.market-news-list').innerText(),/No updates/);await page.getByLabel('Search injury updates').fill('');
  await news.first().locator('summary').click();
  await page.locator('.market-toolbar').scrollIntoViewIfNeeded();await page.evaluate(()=>window.scrollTo(0,document.querySelector('.market-toolbar').getBoundingClientRect().top+scrollY-60));
  await page.waitForTimeout(1500);
  await page.screenshot({path:`outputs/market-fitness-${mobile?'mobile':'desktop'}.png`});
  await page.screenshot({path:`outputs/market-fitness-${mobile?'mobile':'desktop'}-full.png`,fullPage:true});
  if(mobile){await page.locator('.market-fitness-column').scrollIntoViewIfNeeded();await page.evaluate(()=>window.scrollTo(0,document.querySelector('.market-fitness-column').getBoundingClientRect().top+scrollY-65));await page.screenshot({path:'outputs/market-fitness-mobile-news.png'});}
  const loadedPhotos=await page.locator('.market-fitness img').evaluateAll(imgs=>imgs.filter(i=>i.complete&&i.naturalWidth>0).length);assert(loadedPhotos>0);
  const widths=await page.evaluate(()=>({viewport:innerWidth,document:document.documentElement.scrollWidth,table:document.querySelector('.market-table').scrollWidth,container:document.querySelector('.market-table-scroll').clientWidth}));assert(widths.document<=widths.viewport);
  if(!mobile) assert(widths.table<=widths.container+1,'Desktop price table overflows: '+JSON.stringify(widths));
  await page.getByRole('button',{name:'Analysis Live',exact:true}).click();
  await page.getByRole('heading',{name:'Live action',exact:true}).waitFor({timeout:120000});
  await page.locator('.analysis-event-player img').first().scrollIntoViewIfNeeded();
  await page.waitForTimeout(2000);
  const actionPhotos=await page.locator('.analysis-event-player img').evaluateAll(imgs=>imgs.filter(i=>i.complete&&i.naturalWidth>0).length);assert(actionPhotos>0);
  await page.locator('.analysis-feed-controls').scrollIntoViewIfNeeded();await page.evaluate(()=>window.scrollTo(0,document.querySelector('.analysis-feed-controls').getBoundingClientRect().top+scrollY-110));
  await page.screenshot({path:`outputs/live-action-photos-${mobile?'mobile':'desktop'}.png`});
  report.push({mobile,loadedPhotos,actionPhotos,widths,errors});assert.equal(errors.length,0);await context.close();
 }
 await browser.close();fs.writeFileSync('work/market-check-report.json',JSON.stringify(report,null,2));console.log(report);
})().catch(e=>{console.error(e);process.exit(1)});
