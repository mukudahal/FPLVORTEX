import assert from 'node:assert/strict';
import { playerAvailability } from '../ui/availability.js';

const doubtful=playerAvailability({status:'d',news:'Hip injury - 75% chance of playing',chance_of_playing_next_round:75});
assert.equal(doubtful.flagged,true);
assert.equal(doubtful.severity,'doubtful');
assert.equal(doubtful.reason,'Hip injury');
assert.equal(doubtful.nextChance,75);
assert.equal(doubtful.returnText,'No return date published by FPL.','A playing probability never becomes a return date');
const injured=playerAvailability({status:'i',news:'Hamstring injury - Expected back 1 Nov',chance_of_playing_this_round:0,chance_of_playing_next_round:0});
assert.equal(injured.severity,'unavailable');
assert.equal(injured.returnText,'Expected back 1 Nov');
assert.equal(injured.thisChance,0,'Zero is an explicit playing chance, not missing data');
const suspended=playerAvailability({status:'s',news:'Suspended until 31 Oct',news_added:'2026-10-17T16:30:09Z'});
assert.equal(suspended.label,'Suspended');
assert.equal(suspended.severity,'unavailable');
assert.equal(suspended.returnText,'Suspended until 31 Oct');
assert.ok(suspended.updatedAt instanceof Date);
const missing=playerAvailability({status:'i',news:'Back injury - Unknown return date',news_added:'invalid',chance_of_playing_next_round:null});
assert.equal(missing.nextChance,null);
assert.equal(missing.updatedAt,null);
assert.equal(missing.returnText,'No return date published by FPL.');
assert.equal(playerAvailability({status:'a',news:'Old injury report'}).flagged,false,'Old news must not flag a currently available player');
assert.equal(playerAvailability({status:'a',news:'Old injury report'}).severity,'available');
assert.equal(playerAvailability({status:'d',chance_of_playing_next_round:0}).severity,'unavailable');
assert.equal(playerAvailability({status:'d',chance_of_playing_next_round:NaN}).nextChance,null);
assert.equal(playerAvailability({status:'d',chance_of_playing_next_round:-1}).nextChance,null);
assert.equal(playerAvailability(null).flagged,false);
console.log('Availability status, injury/suspension return text, unknown dates and playing-chance regressions passed.');
